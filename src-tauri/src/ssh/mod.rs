/// Clear all transient channels/handles for a session while keeping the
/// reconnect config and reconnect flag (so auto-reconnect can restart).
///
/// Like every cleanup run by a connect attempt or reconnect loop, it only
/// touches the record while `owner` still owns it: after a restart of the
/// same id the record belongs to the new session, which an old task's
/// cleanup must not strip. Returns whether it applied.
async fn cleanup_ssh_runtime_state(state: &SshState, id: &str, owner: &Arc<ReconnectCancellation>) -> bool {
    state
        .with_owned_session(id, owner, |s| {
            s.input_tx = None;
            s.resize_tx = None;
            s.auth_tx = None;
            s.handle = None;
            s.reconnect_prompt_tx = None;
            s.host_key_prompt_tx = None;
        })
        .await
        .is_some()
}

/// Clear transient state plus the reconnect config. Auto-reconnect flag is
/// preserved so the reconnect loop can observe cancellation. Owner-scoped
/// like [`cleanup_ssh_runtime_state`].
async fn cleanup_ssh_session(state: &SshState, id: &str, owner: &Arc<ReconnectCancellation>) -> bool {
    state
        .with_owned_session(id, owner, |s| {
            s.input_tx = None;
            s.resize_tx = None;
            s.auth_tx = None;
            s.handle = None;
            s.reconnect_prompt_tx = None;
            s.host_key_prompt_tx = None;
            s.reconnect_config = None;
        })
        .await
        .is_some()
    // Do NOT clear reconnect_flag here — that's handled only in close_ssh_pty
    // to allow the reconnect loop to restart the connection.
}

/// Stop reconnect loop for a session and clean up all state, finally dropping
/// the entire session record. Returns the record's remote-forward registry so
/// a restart of the same tab can carry its `-R` forwards over.
async fn stop_and_cleanup_ssh_session(state: &SshState, id: &str) -> Option<forwarding::RemoteForwardRegistry> {
    let session = state.sessions.write().await.remove(id)?;
    if let Some(notify) = session.reconnect_flag {
        notify.cancel();
    }
    if let Some(owner) = session.owner {
        owner.cancel();
    }
    // The IO task owns another handle/channel reference. Removing the
    // record alone cannot close it; disconnect also wakes channel.wait().
    if let Some(handle) = session.handle {
        if let Err(error) = handle
            .disconnect(russh::Disconnect::ByApplication, "Session closed", "en").await
        {
            crate::warn_log!("[ssh] {} disconnect failed: {}", id, error);
        }
    }
    session.remote_forwards
}

async fn get_ssh_handle(state: &SshState, id: &str) -> Result<SharedSshHandle, String> {
    state
        .handle(id)
        .await
        .ok_or_else(|| "SSH session is not ready yet".to_string())
}

async fn set_reconnect_session_metadata(
    state: SshState,
    id: String,
    session_name: Option<String>,
    checked_existing_sessions: Option<bool>,
) {
    state
        .with_session_mut(&id, |s| {
            if let Some(config) = s.reconnect_config.as_mut() {
                if let Some(name) = session_name {
                    config.session_name = name;
                }
                if let Some(checked) = checked_existing_sessions {
                    config.checked_existing_sessions = checked;
                }
            }
        })
        .await;
}

async fn open_ssh_channel(
    state: &SshState,
    id: &str,
) -> Result<russh::Channel<client::Msg>, String> {
    let handle = get_ssh_handle(state, id).await?;
    handle
        .channel_open_session()
        .await
        .map_err(|error| format!("Failed to open SSH channel: {error}"))
}


#[tauri::command]
pub async fn answer_ssh_mfa(
    state: State<'_, SshState>,
    id: String,
    responses: Vec<String>,
) -> Result<(), String> {
    // Clone the sender under the read lock so the mpsc awaits run lock-free.
    let tx = state
        .auth_sender(&id)
        .await
        .ok_or_else(|| "Auth response channel not found".to_string())?;
    for response in responses {
        tx.send(response)
            .await
            .map_err(|_| "Failed to send MFA response".to_string())?;
    }
    Ok(())
}

#[tauri::command]
pub async fn answer_ssh_reconnect_choice(
    state: State<'_, SshState>,
    id: String,
    session_name: Option<String>,
) -> Result<(), String> {
    let tx = state
        .reconnect_prompt_sender(&id)
        .await
        .ok_or_else(|| "Reconnect prompt channel not found".to_string())?;

    tx.send(session_name.filter(|value| !value.trim().is_empty()))
        .await
        .map_err(|_| "Failed to send reconnect choice".to_string())
}

