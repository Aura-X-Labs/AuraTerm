#[tauri::command]
pub fn ssh_generate_key_pair(
    passphrase: Option<String>,
    comment: Option<String>,
) -> Result<GeneratedSshKeyPair, String> {
    use russh::keys::{Algorithm, HashAlg, PrivateKey};
    use ssh_key::LineEnding;

    let mut rng = russh::keys::key::safe_rng();
    let mut key = PrivateKey::random(&mut rng, Algorithm::Ed25519)
        .map_err(|error| format!("Failed to generate Ed25519 key: {error}"))?;
    let comment = comment
        .map(|value| value.trim().to_string())
        .filter(|value| !value.is_empty());
    if let Some(comment) = &comment {
        key.set_comment(comment);
    }
    if let Some(passphrase) = passphrase.filter(|value| !value.is_empty()) {
        key = key.encrypt(&mut rng, passphrase.as_bytes())
            .map_err(|error| format!("Failed to encrypt private key: {error}"))?;
    }

    let private_key = key.to_openssh(LineEnding::LF)
        .map_err(|error| format!("Failed to encode private key: {error}"))?
        .to_string();
    let mut public = key.public_key().clone();
    if let Some(comment) = comment {
        public.set_comment(comment);
    }
    let public_key = public.to_openssh()
        .map_err(|error| format!("Failed to encode public key: {error}"))?;
    let fingerprint = public.fingerprint(HashAlg::Sha256).to_string();
    Ok(GeneratedSshKeyPair { private_key, public_key, fingerprint })
}


/// Per-session state consolidated into a single record.
///
/// Previously these fields lived in eight separate `Arc<Mutex<HashMap>>`s,
/// which produced significant lock contention on the keystroke hot path
/// (`write_ssh_pty_input`) and on the IO loop's teardown. We now store the
/// whole per-id record in a single `Arc<RwLock<HashMap<String, SshSessionState>>>`:
///
/// - Hot-path readers (keystroke / resize dispatch) acquire a `read()` lock,
///   clone the cheap `mpsc::Sender` they need, and release the lock before
///   awaiting on the channel `.send()`. Because `Sender` is `Clone` and just
///   bumps an Arc refcount, the read section is O(1) and non-blocking.
/// - Low-frequency mutators (session insert/remove, reconnect metadata
///   update) take a `write()` lock only briefly.
#[derive(Default)]
pub struct SshSessionState {
    /// PTY input forwarder — the channel whose receiver feeds the IO loop.
    input_tx: Option<mpsc::Sender<Vec<u8>>>,
    /// Window-resize forwarder.
    resize_tx: Option<mpsc::Sender<(u32, u32)>>,
    /// MFA / keyboard-interactive answer forwarder.
    auth_tx: Option<mpsc::Sender<String>>,
    /// Reconnect-session-name picker response forwarder.
    reconnect_prompt_tx: Option<mpsc::Sender<Option<String>>>,
    /// Host-key mismatch trust decision forwarder.
    host_key_prompt_tx: Option<mpsc::Sender<bool>>,
    /// Underlying russh handle shared across PTY / SFTP / kill paths.
    handle: Option<SharedSshHandle>,
    /// When `Some`, an auto-reconnect loop is active; notifying it stops the loop.
    reconnect_flag: Option<Arc<ReconnectCancellation>>,
    /// When `Some`, auto-reconnect is enabled and this config is used on every retry.
    reconnect_config: Option<ReconnectConfig>,
    /// Per-session remote (`-R`) forward registry, shared with the russh
    /// `ClientHandler`. Created lazily and reused across reconnects so the
    /// handler always sees the same map.
    remote_forwards: Option<forwarding::RemoteForwardRegistry>,
}

#[derive(Default)]
struct ReconnectCancellation {
    cancelled: AtomicBool,
    notify: Arc<tokio::sync::Notify>,
}

impl ReconnectCancellation {
    fn cancel(&self) {
        self.cancelled.store(true, Ordering::Release);
        self.notify.notify_waiters();
    }

    fn is_cancelled(&self) -> bool {
        self.cancelled.load(Ordering::Acquire)
    }
}

#[derive(Clone)]
pub struct SshState {
    /// Single source of truth for every live SSH session, keyed by the
    /// frontend-assigned connection id.
    sessions: Arc<RwLock<HashMap<String, SshSessionState>>>,
    hub: Arc<crate::terminal_event_hub::TerminalEventHub>,
}

#[derive(Clone)]
struct ReconnectConfig {
    host: String,
    port: u16,
    user: String,
    password: Option<String>,
    private_key: Option<String>,
    passphrase: Option<String>,
    auth_type: Option<String>,
    agent_forwarding: bool,
    jump_hosts: Vec<JumpHostConfig>,
    auto_login_rules: Vec<AutoLoginRule>,
    post_connect_commands: Vec<String>,
    reconnect_type: ReconnectType,
    session_name: String,
    checked_existing_sessions: bool,
    cols: u32,
    rows: u32,
    last_error: Option<String>,
}

#[derive(Clone, Copy, Debug, serde::Serialize, serde::Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum ReconnectType {
    /// Manual reconnect: after disconnect the user can trigger a new connection from the UI.
    Manual,
    /// Reconnect only: no server-side session manager. Running tasks will be lost on disconnect.
    Simple,
    Screen,
    Tmux,
}

impl Default for SshState {
    fn default() -> Self {
        Self::new(Arc::new(crate::terminal_event_hub::TerminalEventHub::new()))
    }
}

impl SshState {
    pub fn new(hub: Arc<crate::terminal_event_hub::TerminalEventHub>) -> Self {
        Self {
            sessions: Arc::new(RwLock::new(HashMap::new())),
            hub,
        }
    }

    pub async fn contains(&self, id: &str) -> bool {
        self.input_sender(id).await.is_some()
    }

    pub async fn write_bytes(&self, id: &str, data: &[u8]) -> Result<(), String> {
        let tx = self.input_sender(id).await.ok_or_else(|| "Connection not found".to_string())?;
        tx.send(data.to_vec()).await.map_err(|_| "SSH connection lost; bytes were not sent".to_string())
    }

    /// Return a snapshot clone of `T` extracted from the session at `id`,
    /// holding only a read lock during the extraction. Used on hot paths.
    async fn snapshot<T, F>(&self, id: &str, f: F) -> Option<T>
    where
        F: FnOnce(&SshSessionState) -> Option<T>,
    {
        let guard = self.sessions.read().await;
        guard.get(id).and_then(f)
    }

    /// Clone the cheap raw-byte sender for PTY input, if any.
    async fn input_sender(&self, id: &str) -> Option<mpsc::Sender<Vec<u8>>> {
        self.snapshot(id, |s| s.input_tx.clone()).await
    }

    /// Clone the cheap `mpsc::Sender<(u32, u32)>` for window resize, if any.
    async fn resize_sender(&self, id: &str) -> Option<mpsc::Sender<(u32, u32)>> {
        self.snapshot(id, |s| s.resize_tx.clone()).await
    }

    /// Clone the MFA response sender, if any.
    async fn auth_sender(&self, id: &str) -> Option<mpsc::Sender<String>> {
        self.snapshot(id, |s| s.auth_tx.clone()).await
    }

    /// Clone the reconnect-prompt response sender, if any.
    async fn reconnect_prompt_sender(
        &self,
        id: &str,
    ) -> Option<mpsc::Sender<Option<String>>> {
        self.snapshot(id, |s| s.reconnect_prompt_tx.clone()).await
    }

    /// Clone the host-key-prompt response sender, if any.
    async fn host_key_prompt_sender(&self, id: &str) -> Option<mpsc::Sender<bool>> {
        self.snapshot(id, |s| s.host_key_prompt_tx.clone()).await
    }

    /// Clone the underlying russh handle, if any.
    async fn handle(&self, id: &str) -> Option<SharedSshHandle> {
        self.snapshot(id, |s| s.handle.clone()).await
    }

    /// Clone the reconnect config, if any.
    async fn reconnect_config(&self, id: &str) -> Option<ReconnectConfig> {
        self.snapshot(id, |s| s.reconnect_config.clone()).await
    }

    /// Mutate an existing session record under the write lock. No-op if
    /// the session has already been cleaned up.
    async fn with_session_mut<F, R>(&self, id: &str, f: F) -> Option<R>
    where
        F: FnOnce(&mut SshSessionState) -> R,
    {
        let mut guard = self.sessions.write().await;
        guard.get_mut(id).map(f)
    }

    /// Ensure a session record exists and apply a mutation closure.
    async fn upsert_session<F>(&self, id: &str, f: F)
    where
        F: FnOnce(&mut SshSessionState),
    {
        let mut guard = self.sessions.write().await;
        let entry = guard.entry(id.to_string()).or_default();
        f(entry);
    }

    /// Get (or lazily create) the per-session remote-forward registry. Used both
    /// by the connect path (handed to the `ClientHandler`) and by the tunnel
    /// commands when registering a remote (`-R`) forward target.
    async fn ensure_remote_forwards(&self, id: &str) -> forwarding::RemoteForwardRegistry {
        let mut guard = self.sessions.write().await;
        let entry = guard.entry(id.to_string()).or_default();
        entry
            .remote_forwards
            .get_or_insert_with(forwarding::new_remote_forward_registry)
            .clone()
    }

    async fn ensure_remote_forwards_owned(self, id: String) -> forwarding::RemoteForwardRegistry {
        self.ensure_remote_forwards(&id).await
    }

    async fn upsert_session_owned<F>(self, id: String, f: F)
    where
        F: FnOnce(&mut SshSessionState) + Send,
    {
        self.upsert_session(&id, f).await;
    }

    /// Read-only access to the remote-forward registry, if one exists.
    async fn remote_forwards_opt(&self, id: &str) -> Option<forwarding::RemoteForwardRegistry> {
        let guard = self.sessions.read().await;
        guard.get(id).and_then(|s| s.remote_forwards.clone())
    }
}

fn shell_escape(value: &str) -> String {
    format!("'{}'", value.replace('\'', "'\"'\"'"))
}

fn build_screen_attach_command(session_name: &str) -> String {
    let escaped_session_name = shell_escape(session_name);
    let screen_term_candidates = [
        "screen.xterm-256color",
        "screen-256color",
        "screen",
        "xterm-256color",
        "vt100",
    ]
    .iter()
    .map(|candidate| shell_escape(candidate))
    .collect::<Vec<_>>()
    .join(" ");
    format!(
        concat!(
            "screen_term=''; ",
            "for candidate in {candidates}; do ",
            "if infocmp \"$candidate\" >/dev/null 2>&1 || TERM=\"$candidate\" tput longname >/dev/null 2>&1; then ",
            "screen_term=\"$candidate\"; break; ",
            "fi; ",
            "done; ",
            "[ -n \"$screen_term\" ] || screen_term='vt100'; ",
            "tmp_rc=$(mktemp /tmp/auraterm-screenrc.XXXXXX 2>/dev/null || mktemp -t auraterm-screenrc.XXXXXX) || exit 1; ",
            "printf '%s\\n%s\\n%s\\n%s\\n' \"term $screen_term\" 'termcapinfo xterm* ti@:te@' 'defscrollback 10000' 'escape ^Bb' > \"$tmp_rc\"; ",
            "printf '\\033[32m[AuraTerm] Screen mode: TERM=%s, wheel scroll and 10000 lines scrollback enabled. Escape key is Ctrl+B.\\033[0m\\n' \"$screen_term\"; ",
            "screen -S {sess} -X eval \"term $screen_term\" 'termcapinfo xterm* ti@:te@' 'defscrollback 10000' 'escape ^Bb' >/dev/null 2>&1 || true; ",
            "screen -T \"$screen_term\" -dr {sess} 2>/dev/null || screen -c \"$tmp_rc\" -T \"$screen_term\" -S {sess}; ",
            "status=$?; rm -f \"$tmp_rc\"; exit $status"
        ),
        sess = escaped_session_name,
        candidates = screen_term_candidates,
    )
}

/// Build the remote command that attaches to (or creates) the tmux session used
/// for reconnect persistence, then enables mouse scrolling. Attaching to an
/// existing session is preferred so a reconnect rejoins the live shell.
fn build_tmux_attach_command(session_name: &str) -> String {
    let sess = shell_escape(session_name);
    format!(
        "tmux new-session -A -s {sess} 2>/dev/null || tmux attach-session -t {sess} 2>/dev/null || tmux new-session -s {sess}; tmux set -g mouse on 2>/dev/null; true"
    )
}

