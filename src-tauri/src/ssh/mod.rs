    #[test]
    fn known_host_scope_round_trips_ipv4_and_hostname() {
        let cases = [
            ("example.com", 22u16),
            ("10.0.0.1", 2222u16),
            ("host-with-dash.internal", 65535u16),
        ];

        for (host, port) in cases {
            let scope = known_host_scope(host, port);
            assert_eq!(scope, format!("{host}:{port}"));

            let parsed = parse_known_host_scope(&scope).expect("scope should parse");
            assert_eq!(parsed, (host.to_string(), port));
        }
    }

    #[test]
    fn parse_known_host_scope_handles_ipv6_with_port_suffix() {
        // rsplit_once(':') intentionally splits on the last colon, which is
        // exactly how `host:port` is preserved even for bracketed IPv6.
        let scope = known_host_scope("[fe80::1]", 22);
        assert_eq!(scope, "[fe80::1]:22");
        let parsed = parse_known_host_scope(&scope).expect("scope should parse");
        assert_eq!(parsed, ("[fe80::1]".to_string(), 22u16));
    }

    #[test]
    fn parse_known_host_scope_rejects_invalid_input() {
        // Missing port
        assert!(parse_known_host_scope("example.com").is_none());
        // Non-numeric port
        assert!(parse_known_host_scope("example.com:http").is_none());
        // Port out of u16 range
        assert!(parse_known_host_scope("example.com:70000").is_none());
        // Empty string
        assert!(parse_known_host_scope("").is_none());
    }

